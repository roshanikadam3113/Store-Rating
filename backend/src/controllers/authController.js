// backend/src/controllers/authController.js
// Authentication controller for NexaPrime Store Rating Application
//
// Handles: register, login, getMe

const bcrypt        = require("bcryptjs");
const User          = require("../models/User");
const generateToken = require("../utils/generateToken");
const {
  validateRegisterInput,
  validateLoginInput,
} = require("../utils/validators");

// ─── Helper — build a safe user object (never include password) ─────────────

/**
 * Returns a plain object with only the fields safe to send to the client.
 * @param {import("mongoose").Document} user  Mongoose User document
 * @returns {object}
 */
function safeUser(user) {
  return {
    _id:       user._id,
    name:      user.name,
    email:     user.email,
    address:   user.address,
    role:      user.role,
    createdAt: user.createdAt,
    updatedAt: user.updatedAt,
  };
}

// ─── Register ────────────────────────────────────────────────────────────────

/**
 * POST /api/auth/register
 * Public route — creates a Normal User account.
 *
 * Security:
 *   - Role is ALWAYS forced to "user" — the client cannot escalate to "owner".
 *   - Any client-supplied `role`, `isAdmin`, or privilege field is ignored.
 *   - Password is validated (length, uppercase, special char) BEFORE hashing.
 *   - Only the bcrypt hash is stored; plaintext is never persisted.
 *   - Duplicate email returns 409, not a Mongoose error leak.
 */
const register = async (req, res, next) => {
  try {
    // ── 1. Validate input ──────────────────────────────────────────────────
    const { errors, normalized } = validateRegisterInput(req.body);
    if (errors.length > 0) {
      return res.status(400).json({ message: errors[0] });
    }

    const { name, email, address, password } = normalized;

    // ── 2. Check for duplicate email ───────────────────────────────────────
    // We check explicitly here so we can return a clean 409 before hitting
    // the MongoDB unique index (which throws code 11000, caught below too).
    const existing = await User.findOne({ email });
    if (existing) {
      return res.status(409).json({ message: "Email is already registered." });
    }

    // ── 3. Hash password (bcrypt salt rounds = 12) ─────────────────────────
    const salt           = await bcrypt.genSalt(12);
    const hashedPassword = await bcrypt.hash(password, salt);

    // ── 4. Create user — ALWAYS role "user" regardless of request body ─────
    const user = await User.create({
      name,
      email,
      address,
      password: hashedPassword,
      role: "user", // Hardcoded — client cannot choose role at registration
    });

    // ── 5. Respond with safe data (no token at registration — login required) ─
    return res.status(201).json({
      message: "Registration successful. Please log in.",
      user:    safeUser(user),
    });
  } catch (err) {
    // Safety net for MongoDB duplicate key race condition
    if (err.code === 11000) {
      return res.status(409).json({ message: "Email is already registered." });
    }
    next(err); // Forward unexpected errors to globalErrorHandler
  }
};

// ─── Login ───────────────────────────────────────────────────────────────────

/**
 * POST /api/auth/login
 * Public route — authenticates Normal Users and Store Owners.
 *
 * Security:
 *   - Email is normalized to lowercase before lookup.
 *   - Invalid credentials always return the same generic message so
 *     attackers cannot enumerate valid emails.
 *   - JWT payload is generated by generateToken utility (not inline).
 *   - Password hash is never included in the response.
 */
const login = async (req, res, next) => {
  try {
    // ── 1. Validate input ──────────────────────────────────────────────────
    const { errors, normalized } = validateLoginInput(req.body);
    if (errors.length > 0) {
      return res.status(400).json({ message: errors[0] });
    }

    const { email, password } = normalized;

    // ── 2. Find user and explicitly select the password hash ───────────────
    // User schema has select:false on password — we opt in here for comparison.
    const user = await User.findOne({ email }).select("+password");

    // ── 3. Verify credentials (generic message prevents email enumeration) ──
    if (!user) {
      return res.status(401).json({ message: "Invalid email or password." });
    }

    const passwordMatch = await bcrypt.compare(password, user.password);
    if (!passwordMatch) {
      return res.status(401).json({ message: "Invalid email or password." });
    }

    // ── 4. Generate JWT ────────────────────────────────────────────────────
    const token = generateToken(user._id, user.role);

    // ── 5. Respond (password field excluded via safeUser helper) ───────────
    return res.status(200).json({
      message: "Login successful.",
      token,
      user: safeUser(user),
    });
  } catch (err) {
    next(err);
  }
};

// ─── Get current user ────────────────────────────────────────────────────────

/**
 * GET /api/auth/me
 * Protected route — returns the profile of the currently authenticated user.
 *
 * req.user is set by the protect middleware (authMiddleware.js).
 * The user is already loaded from the database, so no extra DB call needed.
 * Password is excluded because User schema has select:false.
 */
const getMe = (req, res) => {
  // req.user is a Mongoose document populated by protect middleware
  return res.status(200).json({
    user: safeUser(req.user),
  });
};

// ─── Exports ─────────────────────────────────────────────────────────────────

module.exports = { register, login, getMe };
